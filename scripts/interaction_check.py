"""Exercise the debugging workflow in Chromium without changing production data."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

output = Path('artifacts/interactions')
output.mkdir(parents=True, exist_ok=True)
checks = []
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    context = browser.new_context(viewport={'width': 1440, 'height': 1000}, permissions=['clipboard-read', 'clipboard-write'])
    context.route('https://fonts.googleapis.com/**', lambda route: route.abort())
    page = context.new_page()
    page.goto('http://127.0.0.1:5173/dashboard')
    page.get_by_role('link', name='run_8a41f9c2', exact=True).first.click()
    expect(page).to_have_url('http://127.0.0.1:5173/runs/run_8a41f9c2?stage=validation')
    expect(page.get_by_text('Passed unexpectedly', exact=True)).to_be_visible()
    page.screenshot(path=str(output / 'needs-review.png'), full_page=True)
    checks.append('Attention row opens the relevant validation stage and explains a false negative')

    for theme in ['dark', 'light']:
        page.evaluate(f"localStorage.setItem('tg_theme', '{theme}')")
        for width in [1440, 1100, 390]:
            page.set_viewport_size({'width': width, 'height': 1000})
            page.goto('http://127.0.0.1:5173/runs/run_9f82a4c1')
            expect(page.get_by_role('heading', name='PlannerAgent', exact=True)).to_be_visible()
            expect(page.get_by_text('High confidence', exact=True)).to_be_visible()
            expect(page.get_by_text('Test generated', exact=True)).to_be_visible()
            expect(page.get_by_role('heading', name='Valid regression', exact=True)).to_be_visible()
            assert page.locator('.trace-payload').count() == 0
            assert not page.locator('.disclosure[open]').count()
            assert not page.evaluate('document.documentElement.scrollWidth > innerWidth')
            page.get_by_role('button', name='Decisive step 14', exact=False).click()
            expect(page.locator('#trace-step-14 .trace-payload')).to_be_visible()
            expect(page.locator('#trace-step-14 pre')).to_contain_text('billing_tier_v2')
            expect(page.locator('#trace-step-14 button').first).to_be_focused()
            expect(page.locator('#trace-step-14 button').first).to_be_in_viewport()
            assert page.evaluate('document.documentElement.scrollHeight <= innerHeight + 1'), 'Application content must scroll inside the workspace'
            page.screenshot(path=str(output / f'trace-expanded-{theme}-{width}.png'), full_page=True)
            if width < 1200:
                page.get_by_role('button', name='Stage details', exact=True).click()
            stage_nav = page.get_by_role('navigation', name='Stage detail views')
            stage_nav.get_by_role('button', name='Attribution', exact=True).click()
            page.get_by_text('View model details', exact=True).click()
            expect(page.get_by_text('gpt-4.1-2025-04-14', exact=True)).to_be_visible()
            page.get_by_role('navigation', name='Run pipeline').get_by_role('button', name='Context', exact=False).click()
            page.get_by_text('Context details', exact=True).click()
            expect(page.locator('.stage-pane').get_by_text('Steps 3–8', exact=False)).to_be_visible()
            page.get_by_text('View context manifest', exact=True).click()
            expect(page.get_by_label('Analysis context manifest')).to_contain_text('omitted_ranges')
            page.screenshot(path=str(output / f'context-{theme}-{width}.png'), full_page=True)
            stage_nav.get_by_role('button', name='Regression spec', exact=True).click()
            expect(page.get_by_role('heading', name='Expected behavior', exact=True)).to_be_visible()
            page.get_by_text('View raw specification', exact=True).click()
            expect(page.get_by_label('Raw RegressionSpec')).to_contain_text('regspec.v1')
            page.screenshot(path=str(output / f'regression-spec-{theme}-{width}.png'), full_page=True)
            stage_nav.get_by_role('button', name='Generated test', exact=True).click()
            expect(page.get_by_label('Generated pytest source')).to_contain_text('def test_planner_agent_seq_14_regression')
            lines = page.locator('.generated-panel .code-line')
            assert lines.nth(1).bounding_box()['y'] > lines.nth(0).bounding_box()['y'], 'Source lines must render on separate visual lines'
            page.get_by_role('button', name='Copy', exact=True).click()
            expect(page.get_by_role('button', name='Copied', exact=True)).to_be_visible()
            assert 'def test_planner' in page.evaluate('navigator.clipboard.readText()')
            with page.expect_download() as download:
                page.get_by_role('button', name='Download', exact=True).click()
            assert download.value.suggested_filename.endswith('.py')
            page.get_by_text('Test metadata', exact=True).click()
            expect(page.get_by_text('sha256:', exact=False)).to_be_visible()
            page.screenshot(path=str(output / f'generated-test-{theme}-{width}.png'), full_page=True)
            stage_nav.get_by_role('button', name='Validation', exact=True).click()
            expect(page.get_by_text('Failed as expected', exact=True)).to_be_visible()
            expect(page.get_by_text('Passed as expected', exact=True)).to_be_visible()
            page.get_by_text('Execution details', exact=True).click()
            expect(page.get_by_label('faulty execution diagnostic')).to_contain_text('AssertionError')
            page.screenshot(path=str(output / f'validation-details-{theme}-{width}.png'), full_page=True)
            assert not page.evaluate('document.documentElement.scrollWidth > innerWidth')
            page.get_by_text('More details', exact=True).click()
            expect(page.get_by_role('heading', name='Pipeline timings', exact=True)).to_be_visible()
            assert not page.evaluate('document.documentElement.scrollWidth > innerWidth')
            checks.append(f'Run workflow, evidence focus, context, spec, source copy/download, validation details: {theme} {width}')

    page.goto('http://127.0.0.1:5173/runs')
    page.get_by_role('searchbox').fill('SQLSynthesizer')
    expect(page.locator('tbody tr')).to_have_count(1)
    expect(page.locator('tbody')).to_contain_text('run_7d12a0f8')
    page.get_by_role('searchbox').fill('no-such-run')
    expect(page.get_by_text('No matching runs', exact=True)).to_be_visible()
    page.get_by_role('searchbox').fill('')
    page.get_by_label('Filter by result', exact=True).select_option('validated')
    expect(page.locator('tbody tr')).to_have_count(3)
    checks.append('Search, result filters, and empty results')
    page.set_viewport_size({'width': 390, 'height': 844})
    page.get_by_role('button', name='Toggle menu', exact=True).click()
    expect(page.get_by_role('dialog')).to_be_visible()
    page.keyboard.press('Escape')
    expect(page.get_by_role('dialog')).not_to_be_visible()
    page.get_by_role('button', name='Toggle menu', exact=True).click()
    page.get_by_role('dialog').get_by_role('link', name='System', exact=True).click()
    expect(page.get_by_role('heading', name='System', exact=True)).to_be_visible()
    expect(page.get_by_role('dialog')).not_to_be_visible()
    checks.append('Mobile dialog traps navigation, closes with Escape, and follows routes')
    page.get_by_role('button', name='Toggle menu', exact=True).click()
    page.get_by_role('button', name='Sign out', exact=True).click()
    page.wait_for_url('http://127.0.0.1:5173/')
    page.evaluate("history.pushState({}, '', '/login?next=/runs'); window.dispatchEvent(new PopStateEvent('popstate'))")
    expect(page.get_by_role('heading', name='Sign in to TraceGuard', exact=True)).to_be_visible()
    page.get_by_role('button', name='Continue with GitHub', exact=True).click()
    page.wait_for_url('http://127.0.0.1:5173/runs')
    checks.append('Existing mock sign-out and GitHub sign-in preserve the next route')
    browser.close()
(output / 'results.json').write_text(json.dumps(checks, indent=2))
print(json.dumps(checks, indent=2))
